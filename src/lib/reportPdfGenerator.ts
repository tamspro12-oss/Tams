// Utility: Clean File Name
export function sanitizeFilename(name: string): string {
  return name.replace(/[^a-zA-Z0-9_-]/g, "_").replace(/_+/g, "_");
}

// Draw repeated top header for pages
function drawHeader(
  doc: jsPDF,
  agency: AgencyInfo | undefined,
  reportTitle: string,
  periodText: string,
  partySubtitle?: string
) {
  const pageWidth = doc.internal.pageSize.getWidth();
  
  // Decorative top bar
  doc.setFillColor(15, 23, 42); // Navy Slate
  doc.rect(0, 0, pageWidth, 5, "F");

  // Agency Name
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(15, 23, 42);
  const agencyName = agency?.name || "TAMS PRO ENTERPRISE";
  doc.text(agencyName.toUpperCase(), 14, 15);

  // Agency Contact Details
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  const contacts = [
    agency?.phone_number || agency?.contact_info,
    agency?.contact_email || agency?.email,
    agency?.address || agency?.city,
  ].filter(Boolean).join("  •  ");
  if (contacts) {
    doc.text(contacts, 14, 20);
  }

  // Report Title Badge (Right-aligned)
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(2, 132, 199); // Blue/Sky accent
  doc.text(reportTitle.toUpperCase(), pageWidth - 14, 15, { align: "right" });

  // Period & Subtitle
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  doc.setTextColor(71, 85, 105);
  doc.text(`Period: ${periodText}`, pageWidth - 14, 20, { align: "right" });

  if (partySubtitle) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(15, 23, 42);
    doc.text(`Party: ${partySubtitle}`, 14, 26);
  }

  const generatedTime = format(new Date(), "dd MMM yyyy, HH:mm");
  doc.setFont("helvetica", "italic");
  doc.setFontSize(7.5);
  doc.setTextColor(148, 163, 184);
  doc.text(`Generated: ${generatedTime}`, pageWidth - 14, 25, { align: "right" });

  // Separator Line
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(14, 28, pageWidth - 14, 28);
}

// Draw repeated footer
function drawFooter(doc: jsPDF) {
  const pageCount = (doc as any).getNumberOfPages ? (doc as any).getNumberOfPages() : (doc as any).internal?.pages?.length || 1;
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();

    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.5);
    doc.line(14, pageHeight - 12, pageWidth - 14, pageHeight - 12);

    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(148, 163, 184);
    doc.text("Generated by TAMS Pro • Confidential Accounting Document", 14, pageHeight - 7);
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - 14, pageHeight - 7, { align: "right" });
  }
}

