export interface ExportFinancialOptions {
  agency?: AgencyInfo;
  periodText: string;
  subReport: "pnl" | "accounts_summary" | "assets_dues" | "monthly_income" | "monthly_expenses" | "all";
  asOfDateText?: string;
  pnlData?: FinancialPnlData;
  accountsData?: AccountSummaryRow[];
  assetsDuesData?: AssetDueRow[];
  monthlyIncomeData?: MonthlyFigureRow[];
  monthlyExpensesData?: MonthlyFigureRow[];
}

export function generateFinancialReportsPdf(opts: ExportFinancialOptions): jsPDF {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  if (opts.subReport === "all") {
    // Generate all 5 sub-reports in one comprehensive document
    renderPnlSection(doc, opts.agency, opts.periodText, opts.pnlData, true);
    doc.addPage();
    renderAccountsSummarySection(doc, opts.agency, opts.periodText, opts.accountsData);
    doc.addPage();
    renderAssetsDuesSection(doc, opts.agency, opts.asOfDateText || opts.periodText, opts.assetsDuesData);
    doc.addPage();
    renderMonthlyFiguresSection(doc, opts.agency, opts.periodText, "Monthly Income Trend", opts.monthlyIncomeData, [13, 148, 136]);
    doc.addPage();
    renderMonthlyFiguresSection(doc, opts.agency, opts.periodText, "Monthly Expenses Trend", opts.monthlyExpensesData, [220, 38, 38]);
  } else if (opts.subReport === "pnl") {
    renderPnlSection(doc, opts.agency, opts.periodText, opts.pnlData, false);
  } else if (opts.subReport === "accounts_summary") {
    renderAccountsSummarySection(doc, opts.agency, opts.periodText, opts.accountsData);
  } else if (opts.subReport === "assets_dues") {
    renderAssetsDuesSection(doc, opts.agency, opts.asOfDateText || opts.periodText, opts.assetsDuesData);
  } else if (opts.subReport === "monthly_income") {
    renderMonthlyFiguresSection(doc, opts.agency, opts.periodText, "Monthly Income Report", opts.monthlyIncomeData, [13, 148, 136]);
  } else if (opts.subReport === "monthly_expenses") {
    renderMonthlyFiguresSection(doc, opts.agency, opts.periodText, "Monthly Operating Expenses", opts.monthlyExpensesData, [220, 38, 38]);
  }

  drawFooter(doc);
  return doc;
}

function renderPnlSection(
  doc: jsPDF,
  agency: AgencyInfo | undefined,
  periodText: string,
  pnl?: FinancialPnlData,
  isMultiSection?: boolean
) {
  drawHeader(doc, agency, "Financial Reports - Profit & Loss (Income Statement)", periodText);
  const pageWidth = doc.internal.pageSize.getWidth();

  const rev = pnl?.grossRevenue || 0;
  const cost = pnl?.costOfSales || 0;
  const gp = pnl?.grossProfit || (rev - cost);
  const exp = pnl?.operatingExpenses || 0;
  const ref = pnl?.refunds || 0;
  const net = pnl?.netCleanProfit || (gp - exp - ref);

  const pnlSummaryRows = [
    ["1. Gross Booking Revenue (Invoiced Services)", Number(rev).toLocaleString(), "Revenue (+)"],
    ["2. Less: Cost of Sales (Supplier & Vendor Payables)", Number(cost).toLocaleString(), "Direct Cost (-)"],
    ["3. Gross Profit (Revenue - Direct Costs)", Number(gp).toLocaleString(), "Gross Margin"],
    ["4. Less: Operating Expenses (Administrative & Overhead)", Number(exp).toLocaleString(), "Expenses (-)"],
    ["5. Less: Customer Refunds Issued", Number(ref).toLocaleString(), "Deduction (-)"],
    ["6. NET CLEAN AGENCY PROFIT", Number(net).toLocaleString(), net >= 0 ? "Net Profit" : "Net Loss"],
  ];

  autoTable(doc, {
    startY: 32,
    head: [["Financial Income Statement Item", "Amount (PKR)", "Category"]],
    body: pnlSummaryRows,
    theme: "striped",
    styles: { fontSize: 8.5, cellPadding: 3 },
    headStyles: { fillColor: [15, 23, 42], textColor: [255, 255, 255], fontStyle: "bold" },
    columnStyles: {
      0: { cellWidth: "auto", fontStyle: "bold" },
      1: { cellWidth: 45, halign: "right", fontStyle: "bold" },
      2: { cellWidth: 35, halign: "center" },
    },
    didParseCell: (data) => {
      if (data.section === "body" && data.row.index === 5) {
        data.cell.styles.fillColor = [240, 253, 250]; // Teal accent
        data.cell.styles.fontStyle = "bold";
        if (data.column.index === 1) {
          data.cell.styles.textColor = net >= 0 ? [13, 148, 136] : [220, 38, 38];
        }
      }
    },
  });

  // Operating Expenses Category Breakdown Table
  if (pnl?.expenseBreakdown && pnl.expenseBreakdown.length > 0) {
    const finalY = (doc as any).lastAutoTable.finalY + 8;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(15, 23, 42);
    doc.text("OPERATING EXPENSES BY CATEGORY", 14, finalY);

    const expRows = pnl.expenseBreakdown.map((e, idx) => [
      (idx + 1).toString(),
      e.category || "General",
      Number(e.amount).toLocaleString(),
      rev > 0 ? `${((e.amount / rev) * 100).toFixed(1)}%` : "—",
    ]);

    autoTable(doc, {
      startY: finalY + 3,
      head: [["#", "Expense Category", "Total Expense (PKR)", "% of Revenue"]],
      body: expRows,
      theme: "striped",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [71, 85, 105], textColor: [255, 255, 255], fontStyle: "bold" },
      columnStyles: {
        0: { cellWidth: 10, halign: "center" },
        1: { cellWidth: "auto" },
        2: { cellWidth: 40, halign: "right", fontStyle: "bold" },
        3: { cellWidth: 30, halign: "center" },
      },
    });
  }
}

function renderAccountsSummarySection(
  doc: jsPDF,
  agency: AgencyInfo | undefined,
  periodText: string,
  accounts?: AccountSummaryRow[]
) {
  drawHeader(doc, agency, "Financial Reports - Accounts Summary", periodText);

  let totalDebit = 0;
  let totalCredit = 0;
  let totalClosing = 0;

  const rows = (accounts || []).map((acc, i) => {
    totalDebit += acc.total_debit || 0;
    totalCredit += acc.total_credit || 0;
    totalClosing += acc.closing_balance || 0;

    return [
      (i + 1).toString(),
      acc.account_name,
      acc.account_type.toUpperCase(),
      Number(acc.opening_balance || 0).toLocaleString(),
      Number(acc.total_debit || 0).toLocaleString(),
      Number(acc.total_credit || 0).toLocaleString(),
      Number(acc.closing_balance || 0).toLocaleString(),
    ];
  });

  autoTable(doc, {
    startY: 32,
    head: [["#", "Account Name", "Type", "Opening (PKR)", "Debit (DR)", "Credit (CR)", "Closing Balance (PKR)"]],
    body: rows.length > 0 ? rows : [["—", "No bank or cash accounts found", "—", "0", "0", "0", "0"]],
    theme: "striped",
    styles: { fontSize: 8, cellPadding: 2.5 },
    headStyles: { fillColor: [15, 23, 42], textColor: [255, 255, 255], fontStyle: "bold" },
    columnStyles: {
      0: { cellWidth: 10, halign: "center" },
      1: { cellWidth: "auto", fontStyle: "bold" },
      2: { cellWidth: 20, halign: "center" },
      3: { cellWidth: 28, halign: "right" },
      4: { cellWidth: 28, halign: "right" },
      5: { cellWidth: 28, halign: "right" },
      6: { cellWidth: 34, halign: "right", fontStyle: "bold", textColor: [13, 148, 136] },
    },
  });

  const finalY = (doc as any).lastAutoTable.finalY + 6;
  const pageWidth = doc.internal.pageSize.getWidth();

  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(203, 213, 225);
  doc.roundedRect(14, finalY, pageWidth - 28, 14, 2, 2, "FD");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(8.5);
  doc.setTextColor(15, 23, 42);
  doc.text(`TOTAL LIQUID CASH & BANK POSITION: PKR ${totalClosing.toLocaleString()}`, 18, finalY + 8.5);
}

function renderAssetsDuesSection(
  doc: jsPDF,
  agency: AgencyInfo | undefined,
  asOfText: string,
  items?: AssetDueRow[]
) {
  drawHeader(doc, agency, "Financial Reports - Assets & Dues Position", asOfText);

  let totalCashBank = 0;
  let totalReceivables = 0;
  let totalPayables = 0;

  const rows = (items || []).map((item, i) => {
    if (item.category === "Cash & Bank") totalCashBank += item.amount;
    if (item.category === "Client Receivable") totalReceivables += item.amount;
    if (item.category === "Vendor Payable") totalPayables += item.amount;

    return [
      (i + 1).toString(),
      item.category,
      item.name,
      Number(item.amount).toLocaleString(),
      item.status || "Active",
    ];
  });

  const netAssetPosition = totalCashBank + totalReceivables - totalPayables;

  autoTable(doc, {
    startY: 32,
    head: [["#", "Balance Category", "Account / Party Name", "Amount (PKR)", "Status"]],
    body: rows.length > 0 ? rows : [["—", "No assets or dues records", "—", "0", "—"]],
    theme: "striped",
    styles: { fontSize: 8, cellPadding: 2.5 },
    headStyles: { fillColor: [15, 23, 42], textColor: [255, 255, 255], fontStyle: "bold" },
    columnStyles: {
      0: { cellWidth: 10, halign: "center" },
      1: { cellWidth: 40, fontStyle: "bold" },
      2: { cellWidth: "auto" },
      3: { cellWidth: 35, halign: "right", fontStyle: "bold" },
      4: { cellWidth: 24, halign: "center" },
    },
  });

  const finalY = (doc as any).lastAutoTable.finalY + 6;
  const pageWidth = doc.internal.pageSize.getWidth();

  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(203, 213, 225);
  doc.roundedRect(14, finalY, pageWidth - 28, 22, 2, 2, "FD");

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  doc.text(`Total Liquid Cash & Bank: PKR ${totalCashBank.toLocaleString()}`, 18, finalY + 6);
  doc.text(`Total Client Receivables (Dues): PKR ${totalReceivables.toLocaleString()}`, 18, finalY + 11);
  doc.text(`Total Vendor Payables: PKR ${totalPayables.toLocaleString()}`, 18, finalY + 16);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(netAssetPosition >= 0 ? 13 : 220, netAssetPosition >= 0 ? 148 : 38, netAssetPosition >= 0 ? 136 : 38);
  doc.text(`NET ASSET / SOLVENCY POSITION: PKR ${netAssetPosition.toLocaleString()}`, pageWidth - 18, finalY + 12, {
    align: "right",
  });
}

