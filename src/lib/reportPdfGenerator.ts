export function generateBookingReportPdf(opts: ExportBookingOptions): jsPDF {
  const isLandscape = true;
  const doc = new jsPDF({
    orientation: isLandscape ? "landscape" : "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  drawHeader(doc, opts.agency, "Booking Report & Profit Analysis", opts.periodText);

  let totalSelling = 0;
  let totalCost = 0;
  let totalProfit = 0;

  const tableHead = opts.includeProfit
    ? [["#", "Bill #", "Date", "Client / Pax", "Service", "PNR / Details", "Invoiced (PKR)", "Cost (PKR)", "Profit (PKR)", "Status"]]
    : [["#", "Bill #", "Date", "Client / Pax", "Service", "PNR / Details", "Invoiced (PKR)", "Status"]];

  const tableBody = opts.rows.map((b, i) => {
    totalSelling += Number(b.client_amount) || 0;
    totalCost += Number(b.vendor_payable) || 0;
    totalProfit += Number(b.profit) || 0;

    if (opts.includeProfit) {
      return [
        (i + 1).toString(),
        b.invoice_no || "—",
        b.invoice_date || "—",
        b.client_name || "—",
        b.service || "Booking",
        b.sector_or_pnr || "—",
        Number(b.client_amount || 0).toLocaleString(),
        Number(b.vendor_payable || 0).toLocaleString(),
        Number(b.profit || 0).toLocaleString(),
        b.status || "—",
      ];
    } else {
      return [
        (i + 1).toString(),
        b.invoice_no || "—",
        b.invoice_date || "—",
        b.client_name || "—",
        b.service || "Booking",
        b.sector_or_pnr || "—",
        Number(b.client_amount || 0).toLocaleString(),
        b.status || "—",
      ];
    }
  });

  autoTable(doc, {
    startY: 32,
    head: tableHead,
    body: tableBody,
    theme: "striped",
    styles: {
      fontSize: 8,
      cellPadding: 2.2,
      lineColor: [226, 232, 240],
      lineWidth: 0.2,
    },
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: [255, 255, 255],
      fontStyle: "bold",
    },
    columnStyles: opts.includeProfit
      ? {
          0: { cellWidth: 10, halign: "center" },
          1: { cellWidth: 26, fontStyle: "bold" },
          2: { cellWidth: 22 },
          3: { cellWidth: "auto" },
          4: { cellWidth: 20 },
          5: { cellWidth: 32 },
          6: { cellWidth: 26, halign: "right", fontStyle: "bold" },
          7: { cellWidth: 26, halign: "right" },
          8: { cellWidth: 26, halign: "right", fontStyle: "bold", textColor: [13, 148, 136] },
          9: { cellWidth: 20, halign: "center" },
        }
      : {
          0: { cellWidth: 10, halign: "center" },
          1: { cellWidth: 28, fontStyle: "bold" },
          2: { cellWidth: 24 },
          3: { cellWidth: "auto" },
          4: { cellWidth: 24 },
          5: { cellWidth: 40 },
          6: { cellWidth: 32, halign: "right", fontStyle: "bold" },
          7: { cellWidth: 24, halign: "center" },
        },
  });

  let finalY = (doc as any).lastAutoTable.finalY + 6;

  // Bottom Summary Box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(203, 213, 225);
  doc.setLineWidth(0.3);
  doc.roundedRect(14, finalY, pageWidth - 28, 20, 2, 2, "FD");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(8.5);
  doc.setTextColor(15, 23, 42);
  doc.text(`TOTAL BOOKINGS: ${opts.rows.length}`, 18, finalY + 6);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  doc.text(`Total Gross Sales (Invoiced): PKR ${totalSelling.toLocaleString()}`, 18, finalY + 12);

  if (opts.includeProfit) {
    doc.text(`Total Direct Cost of Sales: PKR ${totalCost.toLocaleString()}`, 120, finalY + 12);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(13, 148, 136);
    doc.text(`Total Gross Profit: PKR ${totalProfit.toLocaleString()}`, pageWidth - 18, finalY + 12, { align: "right" });
  }

  // Quotation Conversion Summary Box (if enabled)
  if (opts.includeQuotationConversion && opts.quotationSummary) {
    finalY += 24;
    doc.setFillColor(240, 253, 250); // Light teal
    doc.setDrawColor(153, 246, 228);
    doc.roundedRect(14, finalY, pageWidth - 28, 14, 2, 2, "FD");

    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(15, 118, 110);
    doc.text("QUOTATION CONVERSION PIPELINE SUMMARY:", 18, finalY + 5.5);

    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(51, 65, 85);
    const qInfo = `Total Quotes: ${opts.quotationSummary.totalQuotes}   |   Accepted: ${opts.quotationSummary.acceptedQuotes}   |   Converted to Invoices: ${opts.quotationSummary.convertedQuotes}   |   Conversion Rate: ${opts.quotationSummary.conversionRate}%`;
    doc.text(qInfo, 18, finalY + 10.5);
  }

  drawFooter(doc);
  return doc;
}

