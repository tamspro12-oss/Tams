export interface ExportDailyReportOptions {
  agency?: AgencyInfo;
  periodText: string;
  receipts: DailyReportRow[];
  payments: DailyReportRow[];
  openingBalance?: number;
  accountType?: string;
}

export function generateDailyReportPdf(opts: ExportDailyReportOptions): jsPDF {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  drawHeader(doc, opts.agency, "Daily Report (Day Book)", opts.periodText, `Account Mode: ${opts.accountType || "Cash & Bank"}`);

  const totalReceipts = opts.receipts.reduce((s, r) => s + (Number(r.amount) || 0), 0);
  const totalPayments = opts.payments.reduce((s, p) => s + (Number(p.amount) || 0), 0);
  const opening = opts.openingBalance || 0;
  const closing = opening + totalReceipts - totalPayments;

  // Day summary top KPI box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(203, 213, 225);
  doc.roundedRect(14, 31, pageWidth - 28, 18, 2, 2, "FD");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  doc.text("OPENING BALANCE", 18, 36);
  doc.text("MONEY IN (RECEIPTS)", 65, 36);
  doc.text("MONEY OUT (PAYMENTS)", 120, 36);
  doc.text("CLOSING BALANCE", pageWidth - 18, 36, { align: "right" });

  doc.setFontSize(9.5);
  doc.setTextColor(15, 23, 42);
  doc.text(`PKR ${opening.toLocaleString()}`, 18, 43);
  doc.setTextColor(5, 150, 105);
  doc.text(`+ PKR ${totalReceipts.toLocaleString()}`, 65, 43);
  doc.setTextColor(220, 38, 38);
  doc.text(`- PKR ${totalPayments.toLocaleString()}`, 120, 43);
  doc.setTextColor(15, 23, 42);
  doc.text(`PKR ${closing.toLocaleString()}`, pageWidth - 18, 43, { align: "right" });

  // Section 1: Receipts Table
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(5, 150, 105);
  doc.text("RECEIPTS (MONEY IN)", 14, 55);

  const receiptsData = opts.receipts.map((r, i) => [
    (i + 1).toString(),
    r.date || "—",
    r.reference_no || "Receipt",
    r.party_name || r.notes || "—",
    (r.method || "Cash").toUpperCase(),
    Number(r.amount || 0).toLocaleString(),
  ]);

  autoTable(doc, {
    startY: 58,
    head: [["#", "Date", "Ref #", "Party / Particulars", "Mode", "Amount (PKR)"]],
    body: receiptsData.length > 0 ? receiptsData : [["—", "—", "No receipts for this period", "—", "—", "0"]],
    theme: "striped",
    styles: { fontSize: 8, cellPadding: 2 },
    headStyles: { fillColor: [5, 150, 105], textColor: [255, 255, 255], fontStyle: "bold" },
    columnStyles: {
      0: { cellWidth: 10, halign: "center" },
      1: { cellWidth: 24 },
      2: { cellWidth: 28, fontStyle: "bold" },
      3: { cellWidth: "auto" },
      4: { cellWidth: 24, halign: "center" },
      5: { cellWidth: 32, halign: "right", fontStyle: "bold" },
    },
  });

  // Section 2: Payments & Expenses Table
  let nextY = (doc as any).lastAutoTable.finalY + 8;
  if (nextY > 230) {
    doc.addPage();
    drawHeader(doc, opts.agency, "Daily Report (Day Book)", opts.periodText);
    nextY = 32;
  }

  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(220, 38, 38);
  doc.text("PAYMENTS & EXPENSES (MONEY OUT)", 14, nextY);

  const paymentsData = opts.payments.map((p, i) => [
    (i + 1).toString(),
    p.date || "—",
    p.reference_no || "Payment",
    p.party_name || p.category || p.notes || "—",
    (p.method || "Cash").toUpperCase(),
    Number(p.amount || 0).toLocaleString(),
  ]);

  autoTable(doc, {
    startY: nextY + 3,
    head: [["#", "Date", "Ref #", "Category / Particulars", "Mode", "Amount (PKR)"]],
    body: paymentsData.length > 0 ? paymentsData : [["—", "—", "No payments for this period", "—", "—", "0"]],
    theme: "striped",
    styles: { fontSize: 8, cellPadding: 2 },
    headStyles: { fillColor: [220, 38, 38], textColor: [255, 255, 255], fontStyle: "bold" },
    columnStyles: {
      0: { cellWidth: 10, halign: "center" },
      1: { cellWidth: 24 },
      2: { cellWidth: 28, fontStyle: "bold" },
      3: { cellWidth: "auto" },
      4: { cellWidth: 24, halign: "center" },
      5: { cellWidth: 32, halign: "right", fontStyle: "bold" },
    },
  });

  drawFooter(doc);
  return doc;
}

