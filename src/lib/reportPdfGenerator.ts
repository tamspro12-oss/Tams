export interface ExportStatementOptions {
  agency?: AgencyInfo;
  periodText: string;
  fromIso: string;
  toIso: string;
  rows: StatementRow[];
  selectedParties: { id: string; name: string; phone?: string; type?: string; opening_balance?: number }[];
  separateParties?: boolean;
  detailedJournalLines?: boolean;
  onlyUnpaid?: boolean;
}

export function generateAccountStatementPdf(opts: ExportStatementOptions): jsPDF {
  const isLandscape = true;
  const doc = new jsPDF({
    orientation: isLandscape ? "landscape" : "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const partyNames = opts.selectedParties.map((p) => p.name).join(", ");
  const isMultiParty = opts.selectedParties.length > 1;

  if (opts.separateParties && isMultiParty) {
    // Each party gets a separate statement on a new page
    opts.selectedParties.forEach((party, idx) => {
      if (idx > 0) doc.addPage();
      const partyRows = opts.rows.filter((r) => r.party_id === party.id || r.party_name === party.name);
      buildSinglePartyStatement(doc, opts.agency, opts.periodText, party.name, party.opening_balance || 0, partyRows, party.type);
    });
  } else {
    // Combined statement or single party
    const subtitle = opts.selectedParties.length === 1 ? opts.selectedParties[0].name : partyNames || "All Parties";
    const initialOpening = opts.selectedParties.length === 1 ? opts.selectedParties[0].opening_balance || 0 : 0;
    buildSinglePartyStatement(doc, opts.agency, opts.periodText, subtitle, initialOpening, opts.rows);
  }

  drawFooter(doc);
  return doc;
}

function buildSinglePartyStatement(
  doc: jsPDF,
  agency: AgencyInfo | undefined,
  periodText: string,
  partySubtitle: string,
  openingBalance: number,
  rows: StatementRow[],
  partyType?: string
) {
  drawHeader(doc, agency, "Account Statement & Ledger", periodText, partySubtitle);
  const pageWidth = doc.internal.pageSize.getWidth();

  let totalDebit = 0;
  let totalCredit = 0;
  let runningBalance = openingBalance;

  const tableBody = rows.map((r, i) => {
    totalDebit += Number(r.debit) || 0;
    totalCredit += Number(r.credit) || 0;
    runningBalance += (Number(r.debit) || 0) - (Number(r.credit) || 0);

    const balanceStr = `${Math.abs(runningBalance).toLocaleString()} ${runningBalance >= 0 ? "DR" : "CR"}`;
    const debitStr = r.debit > 0 ? Number(r.debit).toLocaleString() : "—";
    const creditStr = r.credit > 0 ? Number(r.credit).toLocaleString() : "—";

    return [
      (i + 1).toString(),
      r.date || "—",
      r.voucher_no || "—",
      r.particulars || "—",
      r.entry_type || "Journal",
      debitStr,
      creditStr,
      balanceStr,
      r.overdue_status || "Current",
    ];
  });

  // Opening Balance Row at top of table if opening balance exists
  const openingRow = [
    "—",
    "—",
    "—",
    `OPENING BALANCE AS OF PERIOD START`,
    "Balance B/F",
    openingBalance > 0 ? openingBalance.toLocaleString() : "—",
    openingBalance < 0 ? Math.abs(openingBalance).toLocaleString() : "—",
    `${Math.abs(openingBalance).toLocaleString()} ${openingBalance >= 0 ? "DR" : "CR"}`,
    "—",
  ];

  autoTable(doc, {
    startY: 32,
    head: [["#", "Date", "Voucher #", "Particulars / Description", "Entry Type", "Debit (DR)", "Credit (CR)", "Balance", "Overdue"]],
    body: [openingRow, ...tableBody],
    theme: "striped",
    styles: {
      fontSize: 8,
      cellPadding: 2.2,
      lineColor: [226, 232, 240],
      lineWidth: 0.2,
      valign: "middle",
    },
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: [255, 255, 255],
      fontStyle: "bold",
      fontSize: 8.5,
    },
    columnStyles: {
      0: { cellWidth: 10, halign: "center" },
      1: { cellWidth: 22 },
      2: { cellWidth: 26, fontStyle: "bold" },
      3: { cellWidth: "auto" },
      4: { cellWidth: 22, halign: "center" },
      5: { cellWidth: 28, halign: "right", fontStyle: "bold" },
      6: { cellWidth: 28, halign: "right", fontStyle: "bold" },
      7: { cellWidth: 32, halign: "right", fontStyle: "bold" },
      8: { cellWidth: 24, halign: "center" },
    },
    didParseCell: (data) => {
      // Color overdue red
      if (data.section === "body" && data.column.index === 8) {
        const val = String(data.cell.raw);
        if (val.toLowerCase().includes("overdue") || val.includes("Days")) {
          data.cell.styles.textColor = [220, 38, 38];
          data.cell.styles.fontStyle = "bold";
        }
      }
      // Running balance DR vs CR color
      if (data.section === "body" && data.column.index === 7) {
        const val = String(data.cell.raw);
        if (val.includes("DR")) {
          data.cell.styles.textColor = [185, 28, 28]; // Red/Debit
        } else if (val.includes("CR")) {
          data.cell.styles.textColor = [5, 150, 105]; // Green/Credit
        }
      }
      // Opening row styling
      if (data.section === "body" && data.row.index === 0) {
        data.cell.styles.fillColor = [241, 245, 249];
        data.cell.styles.fontStyle = "bold";
      }
    },
  });

  // Totals & Summary Box
  const finalY = (doc as any).lastAutoTable.finalY + 6;
  const closingBalance = runningBalance;
  const isReceivable = closingBalance > 0;
  const balanceLabel = isReceivable ? "RECEIVABLE FROM PARTY" : closingBalance < 0 ? "PAYABLE TO PARTY" : "SETTLED (NIL)";

  // Summary Container Box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(203, 213, 225);
  doc.setLineWidth(0.3);
  doc.roundedRect(14, finalY, pageWidth - 28, 22, 2, 2, "FD");

  // Summary content
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8.5);
  doc.setTextColor(15, 23, 42);
  doc.text("STATEMENT SUMMARY & CLOSING POSITION", 18, finalY + 5.5);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);
  doc.text(`Total Period Debits (Invoiced/Charges): PKR ${totalDebit.toLocaleString()}`, 18, finalY + 11);
  doc.text(`Total Period Credits (Payments/Receipts): PKR ${totalCredit.toLocaleString()}`, 18, finalY + 16.5);

  // Right Side Closing Balance
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(isReceivable ? 185 : 5, isReceivable ? 28 : 150, isReceivable ? 28 : 105);
  doc.text(`Closing Balance: PKR ${Math.abs(closingBalance).toLocaleString()} ${closingBalance >= 0 ? "DR" : "CR"}`, pageWidth - 18, finalY + 10, {
    align: "right",
  });

  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text(`Status: ${balanceLabel}`, pageWidth - 18, finalY + 16, { align: "right" });
}

